"""Emit web/src/tokens.css, and the docs site's docs/src/styles/tokens.css, from dashboard.tokens.json.

Importing validate.py runs the registry's own gate: an invalid registry prints its
findings and exits 1 before a byte is written, so the generator cannot outrun the
check. Its "registry valid" line is that gate's receipt.

Every token lands in :root as --ds-<token path>; a .light. / .dark. segment in the
path routes it to the light block or the dark @media block instead. A second pass
writes the Tailwind v4 @theme inline mapping (--ds-color-surface -> --color-surface),
so adding a token means editing one file. The --ds- prefix exists because --radius-xl,
--leading-normal and friends are Tailwind theme namespaces: declaring one bare in
:root and aliasing the same name in @theme inline would be self-referential.

The docs site's copy has the same values without the Tailwind mapping. Starlight sets
data-theme on <html> from its own light / dark / auto switch, so the dark block keys on
that attribute rather than on the media query alone.

Output follows the token file's own order, so it is byte-stable. --check renders the
same CSS in memory and diffs it against the committed files instead of writing, so the
drift gate never touches the tree.
Run: python3 designsystem/canyon/build-css.py [--check]
"""
import difflib
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from validate import no_dupes, resolve_tokens  # the registry's own resolver

# token group -> the name Tailwind and hand-written CSS use
NS = {"color": "color", "font": "font", "size": "text", "weight": "font-weight",
      "leading": "leading", "tracking": "tracking", "radius": "radius", "shadow": "shadow",
      "focus": "focus", "motion.duration": "duration", "motion.delay": "delay",
      "motion.easing": "ease", "motion.transform": "motion"}
# the seven self-hosted faces, bundled from web/src/fonts (SIL OFL 1.1, each family's text beside it); the url
# is relative to the output, so Vite hashes each face into /assets — the one static path routed
FACES = [("IBM Plex Sans", "IBMPlexSans", w) for w in (400, 500, 600)] + \
        [("Space Grotesk", "SpaceGrotesk", 600)] + \
        [("JetBrains Mono", "JetBrainsMono", w) for w in (400, 500, 600)]
FILE = {400: "Regular", 500: "Medium", 600: "SemiBold"}
BASE = pathlib.Path(__file__).parent
OUT = BASE.parent.parent / "web" / "src" / "tokens.css"
DOCS_OUT = BASE.parent.parent / "docs" / "src" / "styles" / "tokens.css"
FONTS = BASE.parent.parent / "web" / "src" / "fonts"

missing = [n for n in (f"{stem}-{FILE[w]}.woff2" for _, stem, w in FACES) if not (FONTS / n).exists()]
if missing:
    sys.exit(f"web/src/fonts: missing {', '.join(missing)} — the @font-face rules would 404")

src = json.loads((BASE / "dashboard.tokens.json").read_text(), object_pairs_hook=no_dupes)
tok = resolve_tokens(src, "dashboard.tokens.json")
bare = lambda p: p.replace(".light.", ".").replace(".dark.", ".")
name = lambda p: "--ds-" + bare(p).replace(".", "-")
value = lambda v: ", ".join(f"'{f}'" if " " in f else f for f in v) if isinstance(v, list) else str(v)
block = lambda keys, ind: "".join(f"{ind}{name(k)}: {value(tok[k])};\n" for k in keys)
mode = lambda m: [k for k in tok if f".{m}." in k]
face = lambda fam, stem, w, at="./fonts": (
    f'@font-face {{ font-family: "{fam}"; src: url("{at}/{stem}-{FILE[w]}.woff2") format("woff2");'
    f" font-weight: {w}; font-style: normal; font-display: swap; }}\n")


def alias(path):
    stem = bare(path)
    groups = [g for g in NS if stem.startswith(g + ".")]
    if not groups:
        sys.exit(f"dashboard.tokens.json: {path} is in no token group build-css.py knows — add it to NS")
    group = max(groups, key=len)
    return f"  --{NS[group]}-{stem[len(group) + 1:].replace('.', '-')}: var({name(path)});\n"


NOTICE = ("/* IBM Plex Sans, Space Grotesk and JetBrains Mono, self-hosted. SIL Open Font License 1.1 — web/src/fonts:\n"
          "   LICENSE.txt (IBM Plex), SpaceGrotesk-OFL.txt, JetBrainsMono-OFL.txt. */\n")
shared = [k for k in tok if ".light." not in k and ".dark." not in k]
css = ("/* Generated by designsystem/canyon/build-css.py from dashboard.tokens.json.\n"
       "   Do not edit — CI re-runs the generator and reds on any diff. */\n\n"
       + NOTICE
       + "".join(face(*f) for f in FACES) + "\n"
       ":root {\n" + block(mode("light"), "  ") + "\n" + block(shared, "  ") + "}\n\n"
       "@media (prefers-color-scheme: dark) {\n  :root {\n" + block(mode("dark"), "    ") + "  }\n}\n\n"
       "@theme inline {\n" + "".join(alias(k) for k in mode("light") + shared) + "}\n")
# the docs site resolves @canyon-fonts to docs/src/fonts, a link to web/src/fonts (docs/astro.config.mjs)
docs = ("/* Generated by designsystem/canyon/build-css.py from dashboard.tokens.json.\n"
        "   Do not edit — CI re-runs the generator and reds on any diff. */\n\n"
        + NOTICE
        + "".join(face(*f, at="@canyon-fonts") for f in FACES) + "\n"
        ":root {\n" + block(mode("light"), "  ") + "\n" + block(shared, "  ") + "}\n\n"
        ":root[data-theme='dark'] {\n" + block(mode("dark"), "  ") + "}\n")
for out, want in ((OUT, css), (DOCS_OUT, docs)):
    where = out.relative_to(BASE.parent.parent)
    if "--check" in sys.argv:
        have = out.read_text() if out.exists() else ""
        if have != want:
            sys.stderr.writelines(difflib.unified_diff(
                have.splitlines(True), want.splitlines(True), f"{where} (committed)", f"{where} (generated)"))
            sys.exit(f"{where} is stale or hand-edited — fix the value in dashboard.tokens.json and run 'make tokens'")
        print(f"{where} matches the generator")
    else:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(want)
        print(f"{where}: {len(want)} bytes, {len(mode('light'))} light / {len(mode('dark'))} dark / "
              f"{len(shared)} shared / {len(FACES)} faces")
